    say("=" * 74)
    say("  These audits run against the tables that arrived with the repository.")
    say("  Passing here says the mount is intact. It says nothing yet about")
    say("  whether the container reproduces them (S54 section 10.1).")
    gate_bad = False

    # S54 section 8's FIRST stop condition: dependency resolution not matching
    # 150a means record the difference, fix the image, and do not rerun
    # damaged. Both 2026-09-07/08 runs violated it without anyone noticing,
    # because nothing checked -- the slim image had 42 of the lock's 226
    # packages at the right version and 11 at outright wrong ones, and it took
    # the author asking whether the full closure had been used to surface it
    # (S54 section 9.9). The full image now writes this report at build time;
    # the gate reads it so the rule is enforced by the run rather than by
    # someone remembering to look.
    rep = "/opt/150a_closure_report.tsv"
    if os.path.exists(rep):
        mis = ab = ok = late = 0
        bad = []
        for ln in io.open(rep, encoding="utf-8").read().splitlines()[1:]:
            f = ln.split("	")
            if len(f) < 4:
                continue
            if f[3] == "match":
                ok += 1
            elif f[3] == "later-layer":
                # The build wrote this report before installing cqtna from
                # source, so "later-layer" means "not installed YET, verify
                # now" -- not "ignore me". Counting it as a mismatch failed
                # the gate on a correct image; waving it through would let a
                # genuinely missing package pass. So actually go and look.
                rc_v, out_v = _git_free_version(f[0])
                if rc_v == 0 and out_v == f[1]:
                    ok += 1
                    late += 1
                else:
                    mis += 1
                    bad.append("%s %s -> %s (later-layer, checked at run time)"
                               % (f[0], f[1], out_v or "<absent>"))
            elif f[3] == "absent":
                ab += 1
            else:
                mis += 1
                bad.append("%s %s -> %s" % (f[0], f[1], f[2]))
        say("  150a closure: %d match, %d MISMATCH, %d absent%s" % (ok, mis, ab,
            " (%d verified at run time)" % late if late else ""))
        rows.append(dict(phase=1, step="150a closure",
                         status="ok" if mis == 0 else "MISMATCH", rc=mis))
        if mis:
            for b in bad[:20]:
                say("      %s" % b)
            say("  ⚠ S54 section 8: dependency resolution does not match 150a.")
            say("  Fix the image before rerunning. Not a run to interpret.")
            gate_bad = True
    else:
        say("  ⚠ no /opt/150a_closure_report.tsv in this image, so whether its")
        say("  closure matches 150a is UNVERIFIED. S54 section 8 requires that")
        say("  to be known, not assumed -- this is what section 9.9 records")
        say("  going wrong. Build container/Dockerfile, which writes it.")
        rows.append(dict(phase=1, step="150a closure",
                         status="unverified", rc=-1))
        gate_bad = True

    rc, _ = run("cqtna testthat", ["Rscript", "-e",
                                   'testthat::test_local("cqtna_r")'])
    rows.append(dict(phase=1, step="cqtna testthat",
                     status="ok" if rc == 0 else "FAIL", rc=rc))
    gate_bad |= rc != 0
    for label, cmd in AUDITS:
        rc, _ = run(label + " (pre)", cmd)
        rows.append(dict(phase=1, step=label + " (pre)",
                         status="ok" if rc == 0 else "FAIL", rc=rc))
        gate_bad |= rc != 0
    if gate_bad:
        say()
        say("  GATE FAILED. The environment or the mount is not ready.")
        say("  S54 section 8 forbids going on to explain individual numbers.")
        write_rows(rows)
        return 2

    # ------------------------------------------------------------- phase 2
    say()
    say("=" * 74)
    say("phase 2 -- rerun the analyses; these produce the container's tables")
    say("=" * 74)
    for label, cmd in ANALYSES:
        rc, _ = run(label, cmd)
        rows.append(dict(phase=2, step=label,
                         status="ok" if rc == 0 else "not rerunnable", rc=rc))

    say()
    say("  group 7 -- every other numbered step whose inputs are present")
    cand = []
    for g in GROUP7_GLOBS:
        cand += glob.glob(os.path.join(MR, g))
    cand = sorted(cand)
    cand += [os.path.join(MR, x) for x in GROUP7_EXTRA]
    argv_guard(cand)
    done = set()
    for path in cand:
        name = os.path.basename(path)
        if name in GROUP7_SKIP or name in done or not os.path.exists(path):
            continue
        done.add(name)
        runner = "Rscript" if name.endswith(".R") else "python3"
        rc, _ = run(name, [runner, name, MR], timeout=3600)
        rows.append(dict(phase=2, step=name,
                         status="ok" if rc == 0 else "not rerunnable", rc=rc))

    # ------------------------------------------------------------- phase 3
    say()
    say("=" * 74)
    say("phase 3 -- ACCEPTANCE. The same audits, now against container tables")
    say("=" * 74)
    acc_bad = 0
    for label, cmd in AUDITS:
        rc, _ = run(label + " (post)", cmd)
        rows.append(dict(phase=3, step=label + " (post)",
                         status="ok" if rc == 0 else "FAIL", rc=rc))
        acc_bad += rc != 0

    # ------------------------------------------------------------- phase 4
    say()
    say("=" * 74)
    say("phase 4 -- container tables against the phase-0 baseline")
    say("=" * 74)
    watch_guard()
    say()
    moved, diffs = [], []
    for f in WATCH:
        a, b = os.path.join(BASE, f), os.path.join(MR, f)
        if not os.path.exists(a) or not os.path.exists(b):
            continue
        if filecmp.cmp(a, b, shallow=False):
            continue
        moved.append(f)
        for where, was, now in cellwise_diff(a, b):
            diffs.append(dict(table=f, where=where, baseline=was, container=now))
    if not moved:
        say("  every watched table is byte-identical to the baseline.")
    else:
        say("  %d table(s) differ:" % len(moved))
        for f in moved:
            n = sum(1 for d in diffs if d["table"] == f)
            say("    %-44s %d changed cell(s)" % (f, n))
    with io.open(os.path.join(MR, "159e_table_diff.tsv"), "w",
                 encoding="utf-8", newline="\n") as fh:
        fh.write("table\twhere\tbaseline\tcontainer\n")
        for d in diffs:
            fh.write("%s\t%s\t%s\t%s\n"
                     % (d["table"], d["where"], d["baseline"], d["container"]))
    say("  wrote 159e_table_diff.tsv")

    write_rows(rows)
    say()
    say("=" * 74)
    if acc_bad:
        say("VERDICT: %d audit(s) FAILED in phase 3." % acc_bad)
        say("Those failures are the numbers that moved. Enumerate every one in")
        say("S54 section 9.2 and every flipped verdict in 9.3, then apply the")
        say("migration rule in S54 section 5. Do not adopt selectively:")
        say("S54 section 4 is all-or-nothing.")
        return 1
    say("VERDICT: phase 3 audits all pass against container-produced tables,")
    say("and %d watched table(s) differ from the baseline." % len(moved))
    say()
    say("This is still NOT a decision. Read 159e_table_diff.tsv, fill S54")
    say("section 9, and choose canonical or fall back to (a) with reasons.")
    return 0


