def argv_guard(paths):
    """Does any script mean something OTHER than the repository by argv[1]?

    This runner invokes every group-7 script as `<runner> <script> <MR>`, so it
    is asserting that argv[1] is the repository directory. The 2026-09-11
    portability pass then gave 102 scripts `MR = sys.argv[1] ...` on that
    assumption -- and two of them already used argv[1] for something else:
    step91 reads it as the path to a PMID JSON, step21 as a ligand-receptor
    table (with argv[2] as a tag). Both would have silently set MR to a
    filename on the authoring machine.

    The check that passed those two was the wrong kind: it verified the SHAPE
    of every changed line and reported zero violations, which says nothing
    about what argv[1] already meant. So the check lives here now, next to the
    call that makes the assumption, rather than in a one-off script someone
    has to remember to run.
    """
    bad = []
    for p in paths:
        if not p.endswith(".py") or not os.path.exists(p):
            continue
        try:
            s = io.open(p, encoding="utf-8", errors="replace").read()
        except Exception:
            continue
        m = re.search(r'MR\s*=\s*\(?sys\.argv\[(\d)\]', s)
        if not m:
            continue
        idx = m.group(1)
        rest = s[m.end():]
        if re.search(r'sys\.argv\[%s\]' % idx, rest):
            bad.append((os.path.basename(p), idx))
    if bad:
        say("  ⚠ argv guard: %d script(s) read argv[%s] for something other"
            % (len(bad), ", ".join(sorted({b[1] for b in bad}))))
        say("    than the repository, and would take this runner's MR for it:")
        for n, i in bad:
            say("      %-44s argv[%s] reused" % (n, i))
        say("    Give MR the next free index, as step157/step158 do.")
    else:
        say("  argv guard: no script reuses the index it takes MR from.")


def watch_guard():
    """Every table step127 reconciles the manuscript against must be watched.

    S54 section 2's tier-one criterion is "every number the text cites", and
    phase 4 is what reports a number that moved. A table step127 reads but
    WATCH omits is therefore invisible to phase 4 -- the acceptance still
    passes, and the moved value is simply never mentioned. That happened:
    126c_permutation_primary.tsv, the permutation calibration, was audited by
    step127 and absent from WATCH, and it took a hand comparison to notice.
    Rather than add the one name and move on, this derives the set from
    step127's own source so the next table added there cannot slip through.
    """
    src_path = os.path.join(MR, "step127_audit_manuscript_numbers.py")
    try:
        src = io.open(src_path, encoding="utf-8").read()
    except Exception as e:
        say("  WATCH guard: cannot read step127 (%s); guard skipped." % e)
        return
    reads = set(re.findall(r'["\']([0-9]{2,3}[a-z]_[A-Za-z0-9_]+\.tsv)["\']', src))
    missing = sorted(reads - set(WATCH))
    if missing:
        say("  ⚠ WATCH guard: step127 audits %d table(s) phase 4 does not"
            " compare:" % len(missing))
        for m in missing:
            say("      %s" % m)
        say("    A number that moved in these would pass unreported. Add them")
        say("    to WATCH.")
    else:
        say("  WATCH guard: all %d table(s) step127 audits are watched." % len(reads))


def _git(args):
    try:
        p = subprocess.run(["git"] + args, cwd=MR, capture_output=True,
                           text=True, timeout=60)
        return p.returncode, (p.stdout or "")
    except Exception:
        return 1, ""


def _git_free_version(pkg):
    """Installed version of an R package, or ("", None) if it is not there."""
    try:
        p = subprocess.run(
            ["Rscript", "-e",
             'cat(as.character(packageVersion("%s")))' % pkg],
            cwd=MR, capture_output=True, text=True, timeout=120)
        return p.returncode, (p.stdout or "").strip()
    except Exception:
        return 1, ""


def run(label, cmd, timeout=7200):
    # A step that cannot succeed here should not be able to leave tracked
    # files worse off than it found them. Discovered the hard way: step158
    # failed for a documented, legitimate reason (its external inputs are not
    # part of the deposit) and, in doing so, overwrote 158c_console.log --
    # 33 lines of a prior successful run's evidence -- with one line saying
    # it could not run this time. Nothing was lost from git history, but a
    # tool meant to be rerun by strangers should not depend on a human
    # noticing that in every future run. `git diff --name-only` before and
    # after brackets exactly what THIS step touched; on failure, revert only
    # that set, never anything a different step is responsible for.
    rc_git, before = _git(["diff", "--name-only"])
    before = set(before.split()) if rc_git == 0 else None

    t0 = time.time()
    try:
        p = subprocess.run(cmd, cwd=MR, capture_output=True, text=True,
                           timeout=timeout)
        rc, out = p.returncode, (p.stdout or "") + (p.stderr or "")
    except FileNotFoundError as e:
        rc, out = 127, "not found: %s" % e
    except subprocess.TimeoutExpired:
        rc, out = 124, "timed out"
    say("  %-34s %-12s %6.1f s"
        % (label, "ok" if rc == 0 else "FAIL rc=%d" % rc, time.time() - t0))
    if rc != 0:
        for line in [x for x in out.splitlines() if x.strip()][-8:]:
            say("      | " + line[:108])
        if before is not None:
            rc_git, after = _git(["diff", "--name-only"])
            touched = (set(after.split()) - before) if rc_git == 0 else set()
            if touched:
                _git(["checkout", "--"] + sorted(touched))
                say("      reverted (failed step touched tracked files): %s"
                    % ", ".join(sorted(touched)))
    return rc, out


def cellwise_diff(a, b, limit=40):
    """Report changed cells, not just changed files: a moved digit is what S54
    section 5 has to enumerate."""
    try:
        ra = io.open(a, encoding="utf-8", errors="replace").read().split("\n")
        rb = io.open(b, encoding="utf-8", errors="replace").read().split("\n")
    except Exception as e:
        return [("<unreadable>", "", str(e))]
    out = []
    if ra and rb and ra[0] != rb[0]:
        out.append(("<header>", ra[0][:60], rb[0][:60]))
    for i in range(max(len(ra), len(rb))):
        la = ra[i] if i < len(ra) else "<missing row>"
        lb = rb[i] if i < len(rb) else "<missing row>"
        if la == lb:
            continue
        ca, cb = la.split("\t"), lb.split("\t")
        for j in range(max(len(ca), len(cb))):
            x = ca[j] if j < len(ca) else ""
            y = cb[j] if j < len(cb) else ""
            if x != y:
                out.append(("row %d col %d" % (i, j + 1), x[:40], y[:40]))
                if len(out) >= limit:
                    return out
    return out


